'use strict';
const assert=require('node:assert/strict');
const {requestRecall,allowed,closeRecall,EMERGENCY,CLOSED}=require('./guards');
const initial={eventId:'E1',phase:'FIELD_ACTIVE'};
assert.throws(()=>requestRecall(initial,'FOP','E1','ABBRECHEN'),/ROLE_DENIED/);
assert.throws(()=>requestRecall(initial,'FOUNDER','E2','ABBRECHEN'),/EVENT_MISMATCH/);
assert.throws(()=>requestRecall(initial,'FOUNDER','E1',''),/CONFIRMATION_REQUIRED/);
const recall=requestRecall(initial,'FOUNDER','E1','ABBRECHEN');
assert.equal(recall.phase,EMERGENCY);
assert.equal(requestRecall(recall,'FOUNDER','E1','ABBRECHEN').replayed,true);
for(const action of ['EXCHANGE','CATCH','RESTORE','RE_SUPPLY','UPLOAD','INSTALL','EVAC_START','NODE_ACCESS'])assert.equal(allowed(recall,action),false,action);
for(const action of ['FOP_DEINSTALL','FOP_CORE_SCAN','FOP_RECOVERY_CONFIRM','FOUNDER_RECALL_STATUS','AUDIT_READ'])assert.equal(allowed(recall,action),true,action);
assert.throws(()=>closeRecall(recall,{nodes:[{status:'ACTIVE'}],cores:[],openOrders:[]}),/NODE_RECOVERY_INCOMPLETE/);
assert.throws(()=>closeRecall(recall,{nodes:[{status:'DEINSTALLED'}],cores:[{ownerType:'NODE'}],openOrders:[]}),/CORE_RECOVERY_INCOMPLETE/);
assert.throws(()=>closeRecall(recall,{nodes:[],cores:[],openOrders:['pending']}),/OPEN_OPERATIONS/);
const closed=closeRecall(recall,{nodes:[{status:'DEINSTALLED'}],cores:[{ownerType:'NODIV_RESERVE'}],openOrders:[]});
assert.equal(closed.phase,CLOSED);
assert.equal(allowed(closed,'FOP_DEINSTALL'),false);
console.log('FORCE RECALL isolated guard tests: PASS');
